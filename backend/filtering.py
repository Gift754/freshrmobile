"""Decide which files in a repo are worth analysing.

Drops vendored/build directories, lockfiles, binaries, minified or generated code,
well-known library files and (optionally) files that match known scaffold templates.
"""
import hashlib
import os
import re

VENDOR_DIRS = {
    "node_modules", "vendor", "third_party", "third-party", "bower_components", "dist", "build",
    "out", "target", ".next", ".nuxt", ".svelte-kit", ".venv", "venv", "env", "__pycache__",
    "site-packages", "Pods", "Carthage", ".gradle", ".idea", ".vscode", "coverage", ".git",
    "wp-admin", "wp-includes", "migrations_old", "bin", "obj", ".dart_tool", ".pub-cache",
    "DerivedData", "__MACOSX", "staticfiles", "static_root",
}
LOCKFILES = {
    "package-lock.json", "yarn.lock", "pnpm-lock.yaml", "composer.lock", "Gemfile.lock",
    "poetry.lock", "Pipfile.lock", "Cargo.lock", "go.sum", "pubspec.lock", "gradlew",
    "gradlew.bat", "mvnw", "mvnw.cmd", "bun.lockb",
}
BINARY_EXT = {
    ".png", ".jpg", ".jpeg", ".gif", ".webp", ".ico", ".svg", ".pdf", ".zip", ".tar", ".gz",
    ".woff", ".woff2", ".ttf", ".eot", ".otf", ".mp3", ".mp4", ".mov", ".exe", ".dll", ".so",
    ".class", ".jar", ".pyc", ".o", ".a", ".bin", ".map", ".psd", ".ai", ".fig", ".sketch",
}
LIB_FILE_RE = re.compile(
    r"^(jquery|bootstrap|popper|lodash|moment|angular|react|react-dom|vue|d3|three|chart|axios|"
    r"fontawesome|font-awesome|slick|owl\.carousel|swiper|select2|datatables)[.\-].*\.(js|css)$", re.I)
BOILERPLATE_NAMES = {
    "reportWebVitals.js", "setupTests.js", "serviceWorker.js", "registerServiceWorker.js",
    "App.test.js", "App.test.tsx", "vite-env.d.ts", "next-env.d.ts",
}
GENERATED_RE = re.compile(
    r"(auto[- ]?generated|generated by|do not edit|@generated|code generated|this file is generated)", re.I)

LANG_EXT = {
    ".py": "Python", ".js": "JavaScript", ".jsx": "JavaScript", ".mjs": "JavaScript",
    ".cjs": "JavaScript", ".ts": "TypeScript", ".tsx": "TypeScript", ".java": "Java",
    ".kt": "Kotlin", ".kts": "Kotlin", ".swift": "Swift", ".c": "C", ".h": "C",
    ".cpp": "C++", ".cc": "C++", ".cxx": "C++", ".hpp": "C++", ".cs": "C#", ".go": "Go",
    ".rs": "Rust", ".php": "PHP", ".rb": "Ruby", ".dart": "Dart", ".sql": "SQL",
    ".html": "HTML", ".htm": "HTML", ".css": "CSS", ".scss": "CSS", ".sass": "CSS",
    ".less": "CSS", ".sh": "Shell", ".bash": "Shell", ".vue": "Vue", ".svelte": "Svelte",
    ".gd": "GDScript", ".ino": "Arduino",
}


def skip_reason(rel_path):
    """Path-level filter. Returns a reason string, or None if the file should be kept."""
    parts = rel_path.replace("\\", "/").split("/")
    name = parts[-1]
    if any(p in VENDOR_DIRS for p in parts[:-1]):
        return "vendored/build directory"
    if name in LOCKFILES:
        return "lockfile"
    if name.endswith((".min.js", ".min.css")):
        return "minified"
    if os.path.splitext(name)[1].lower() in BINARY_EXT:
        return "binary/asset"
    if LIB_FILE_RE.match(name):
        return "bundled library"
    if name in BOILERPLATE_NAMES:
        return "scaffold boilerplate"
    return None


def read_text(path, max_bytes=1_000_000):
    """Read a file as text; None if too large, unreadable or binary."""
    try:
        if os.path.getsize(path) > max_bytes:
            return None
        with open(path, "rb") as fh:
            data = fh.read()
    except OSError:
        return None
    if b"\0" in data[:4096]:
        return None
    return data.decode("utf-8", errors="ignore")


def content_hash(text):
    return hashlib.sha1(re.sub(r"\s+", "", text).encode("utf-8", "ignore")).hexdigest()


def content_skip_reason(text, template_hashes=None):
    """Content-level filter: generated, minified or known scaffold files."""
    lines = text.splitlines()
    if GENERATED_RE.search("\n".join(lines[:10])):
        return "generated"
    if lines and (max(len(l) for l in lines) > 1000 or (len(lines) < 20 and len(text) / len(lines) > 200)):
        return "minified"
    if template_hashes and content_hash(text) in template_hashes:
        return "known scaffold template"
    return None
